#!/bin/bash
# Fixture: one approved scenario and its spec. The spec matches the scenario.
set -e
mkdir -p e2e-scenarios/auth/login
cat > e2e-scenarios/e2e.config.json <<'JSON'
{
  "baseURL": "http://localhost:3000",
  "auth": "none"
}
JSON
cat > e2e-scenarios/auth/login/scenario.md <<'MD'
# Login Flow

Standard authentication flow for the application.

Covers: #1024

## Context

- User must NOT be authenticated

---

## Scenario: Failed login with wrong password

### Description

Enter a valid email but an incorrect password. The form should show
an error without clearing the email field.

### Expected

1. Stays on /login
2. Error message "Invalid credentials" is visible
3. Email field retains the entered value
MD
cat > e2e-scenarios/auth/login/scenario.spec.ts <<'TS'
// Generated by /e2e:run. The scenario file is the contract.
// scenario: e2e-scenarios/auth/login/scenario.md
// scenario-sha256: 22492952913b200fced6496f756b64e1550ad4e3e526e441ddc1dce3fe558933
import { test, expect } from "@playwright/test";

// Test data. Change these values for your environment.
const EMAIL = "qa@example.com";
const WRONG_PASSWORD = "not-the-password";

test.use({ storageState: { cookies: [], origins: [] } });

test.describe("Login Flow", { annotation: [{ type: "covers", description: "#1024" }] }, () => {
  test("Failed login with wrong password", async ({ page }) => {
    await page.goto("/");
    await page.getByRole("textbox", { name: "Email" }).fill(EMAIL);
    await page.getByRole("textbox", { name: "Password" }).fill(WRONG_PASSWORD);
    await page.getByRole("button", { name: "Sign in" }).click();

    await test.step("E1: Stays on /login", async () => {
      await expect(page).toHaveURL(/\/login$/);
    });
    await test.step('E2: Error message "Invalid credentials" is visible', async () => {
      await expect(page.getByRole("alert")).toHaveText("Invalid credentials");
    });
    await test.step("E3: Email field retains the entered value", async () => {
      await expect(page.getByRole("textbox", { name: "Email" })).toHaveValue(EMAIL);
    });
  });
});
TS

# The spec is committed, as in a real project. The plugin then treats it as established.
git init -q
git add -A
git -c user.name=fixture -c user.email=fixture@example.com commit -q -m "Add the login scenario and its spec"
